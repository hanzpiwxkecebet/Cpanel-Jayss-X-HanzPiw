'use strict';
const path = require('path');
const { fbRead, fbWrite } = require('./firebase');

const LANG_FILE = path.join(__dirname, '..', 'database', 'user_lang.json');

function getUserLang(userId) {
  return fbRead(LANG_FILE, {})[String(userId)] || 'en';
}
function setUserLang(userId, lang) {
  const d = fbRead(LANG_FILE, {});
  d[String(userId)] = lang;
  fbWrite(LANG_FILE, d);
}

